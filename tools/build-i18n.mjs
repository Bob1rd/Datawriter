#!/usr/bin/env node
// Builds extension/i18n.js from the string catalogs in tools/i18n/.
//   en.json is the source catalog; es.json and zh_CN.json are the translations (same keys).
//   runtime.js is the language-switching code that ships with the tables.
// Run from anywhere:  node tools/build-i18n.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'i18n');
const out = join(here, '..', 'extension', 'i18n.js');
const LANGS = ['en', 'es', 'zh_CN'];

const tables = {};
for (const lang of LANGS) tables[lang] = JSON.parse(readFileSync(join(src, `${lang}.json`), 'utf8'));

// Every translation must carry exactly the English keys, so a missing string can never fall back silently.
const enKeys = Object.keys(tables.en);
let bad = false;
for (const lang of LANGS.slice(1)) {
  const keys = new Set(Object.keys(tables[lang]));
  const missing = enKeys.filter((k) => !keys.has(k));
  const extra = [...keys].filter((k) => !(k in tables.en));
  if (missing.length) { bad = true; console.error(`${lang}.json is missing: ${missing.join(', ')}`); }
  if (extra.length) { bad = true; console.error(`${lang}.json has keys not in en.json: ${extra.join(', ')}`); }
  // Placeholders like {n} must survive translation.
  for (const k of enKeys) {
    if (!keys.has(k)) continue;
    const slots = (s) => (String(s).match(/\{\w+\}/g) || []).sort().join(' ');
    if (slots(tables.en[k]) !== slots(tables[lang][k])) { bad = true; console.error(`${lang}.json ${k}: placeholders differ from en.json`); }
  }
}
if (bad) process.exit(1);

const runtime = readFileSync(join(src, 'runtime.js'), 'utf8');
const header = [
  '// Generated by tools/build-i18n.mjs from tools/i18n/en.json, es.json and zh_CN.json.',
  '// Do not edit by hand. Loaded before every other script on trackdatacenters.com, and by popup.html and about.html.',
].join('\n');
const body = runtime.replace('  /*TABLES*/', `  const TABLES = ${JSON.stringify(tables)};`);
writeFileSync(out, `${header}\n${body}`);
console.log(`wrote ${out}: ${enKeys.length} strings × ${LANGS.length} languages`);
